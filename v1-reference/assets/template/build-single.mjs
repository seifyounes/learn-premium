/* build-single.mjs
   Bundles the whole static site into ONE self-contained HTML file
   (all CSS + JS + content inlined) so it can be uploaded to any static host
   as a single index.html. Run:  node build-single.mjs
   Output: dist/index.html
*/
import { promises as fs } from "fs";
import path from "path";
import { fileURLToPath } from "url";

const ROOT = path.dirname(fileURLToPath(import.meta.url));
const OUT_DIR = path.join(ROOT, "dist");
const OUT = path.join(OUT_DIR, "index.html");

const read = (p) => fs.readFile(path.join(ROOT, p), "utf8");
// neutralise any literal </script> inside inlined JS so the browser doesn't end the block early
const safe = (js) => js.replace(/<\/script>/gi, "<\\/script>");

let html = await read("index.html");

// 1) inline the stylesheet
// NOTE: use a REPLACER FUNCTION everywhere — a string replacement would interpret
// "$" sequences ($$, $&, $1...) inside the JS/CSS and corrupt the code.
let css = await read("css/styles.css");

/* 1a) inline every asset the CSS references as a data URI, or the single-file
   build silently loses its imagery the moment index.html is moved anywhere.
   Fails loudly on a missing file — a broken url() is invisible in a dark theme. */
const MIME = { jpg: "image/jpeg", jpeg: "image/jpeg", png: "image/png", svg: "image/svg+xml", webp: "image/webp", gif: "image/gif" };
const urlRe = /url\(\s*["']?(\.\.\/)?(assets\/[^"')]+)["']?\s*\)/gi;
const assets = [...new Set([...css.matchAll(urlRe)].map(m => m[2]))];
for (const rel of assets) {
  const ext = path.extname(rel).slice(1).toLowerCase();
  const mime = MIME[ext];
  if (!mime) throw new Error(`build: no MIME type known for asset ${rel}`);
  const b64 = (await fs.readFile(path.join(ROOT, rel))).toString("base64");
  const kb = (b64.length / 1024).toFixed(0);
  css = css.replace(new RegExp(`url\\(\\s*["']?(\\.\\./)?${rel.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}["']?\\s*\\)`, "gi"),
    () => `url("data:${mime};base64,${b64}")`);
  console.log(`  inlined ${rel} (${kb} KB base64)`);
}

html = html.replace(/<link\s+rel="stylesheet"\s+href="css\/styles\.css"\s*\/?>/i,
  () => `<style>\n${css}\n</style>`);

// 2) inline every <script src="..."></script> in document order
const scriptRe = /<script\s+src="([^"]+)"><\/script>/gi;
const srcs = [];
let mm;
while ((mm = scriptRe.exec(html))) srcs.push(mm[1]);

for (const src of srcs) {
  const code = safe(await read(src));
  html = html.replace(`<script src="${src}"></script>`, () => `<script>\n${code}\n</script>`);
}

// 3) tidy header comment
html = html.replace(/<title>/, `<!-- Crash Course — single-file build. Generated by build-single.mjs. -->\n<title>`);

await fs.mkdir(OUT_DIR, { recursive: true });
await fs.writeFile(OUT, html, "utf8");

const kb = (Buffer.byteLength(html, "utf8") / 1024).toFixed(0);
console.log(`Wrote ${path.relative(ROOT, OUT)}  (${kb} KB, ${srcs.length} scripts + CSS inlined)`);
console.log("Deploy dist/index.html — Vercel (outputDirectory scoped to dist/) or Netlify Drop both take it.");
